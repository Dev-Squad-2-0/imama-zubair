"""
Day 3 - Task 5: Human Evaluation - Transcript Generation

Runs a set of scripted call scenarios through the full conversation_agent.py
pipeline (memory + objections + retrieval + recommendation + speech behaviors
+ voice pipeline latency) and writes out transcripts with per-turn latency,
so they can be scored by a human against the rubric in human_eval_rubric.md.

This does not produce actual audio (no live phone line / TTS credentials in
this environment). What's recorded is exactly what would be spoken to the
caller and how long it took to start speaking, which is what the rubric
scores (naturalness, persuasiveness, fluency of the text, latency, flow).
"""

import os
import sys
import json

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from conversation_memory import ConversationMemory
from speech_behaviors import SpeechBehaviorLayer
from conversation_agent import run_turn

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "outputs")
os.makedirs(OUT_DIR, exist_ok=True)


SCENARIOS = {
    "scenario_1_budget_and_area_memory": [
        "Assalam o alaikum, mujhe Lahore mein ghar dekhna hai.",
        "Budget 3 crore hai.",
        "DHA mein kya options hain?",
        "Us se sasti koi option?",
    ],
    "scenario_2_price_objection_then_decline_twice": [
        "Karachi mein rent ke liye apartment chahiye.",
        "Yeh property thori mehngi hai.",
        "Nahi, mujhe nahi chahiye.",
        "Nahi thanks, abhi nahi.",
    ],
    "scenario_3_investment_guardrail": [
        "Investment ke liye property dekh raha hoon Lahore mein.",
        "Investment ke hisaab se kitna profit hoga guaranteed?",
    ],
    "scenario_4_trust_and_builder_concerns": [
        "DHA Phase 6 mein 10 marla house dekh raha hoon.",
        "Mujhe is builder par bharosa nahi.",
        "Monthly maintenance kitni hai is society ki?",
    ],
    "scenario_5_interruption_midcall": [
        "Assalam o alaikum, mujhe Lahore mein 5 marla ghar chahiye buy ke liye.",
        "__INTERRUPTION__",
        "Sorry, main keh raha tha budget 2 crore hai.",
    ],
}


def run_scenario(name, turns):
    memory = ConversationMemory()
    behaviors = SpeechBehaviorLayer(seed=hash(name) % 1000)
    transcript = [f"## {name}\n"]
    latencies = []

    for t in turns:
        if t == "__INTERRUPTION__":
            spoken, report = run_turn("", memory, behaviors, interrupted=True)
            transcript.append(f"**[customer barges in while agent is speaking]**")
            transcript.append(f"**AGENT:** {spoken}\n")
            continue

        transcript.append(f"**CUSTOMER:** {t}")
        spoken, report = run_turn(t, memory, behaviors)
        transcript.append(f"**AGENT:** {spoken}")
        if report:
            transcript.append(
                f"*(latency to first audio: {report.total_first_audio_ms}ms - "
                f"{'within' if report.under_budget else 'OVER'} 2000ms budget)*\n"
            )
            latencies.append(report.total_first_audio_ms)
        else:
            transcript.append("")

    return "\n".join(transcript), latencies


def main():

    all_latencies = []
    full_output = ["# Day 3 - Sample Call Transcripts\n",
                    "Generated by `eval/sample_conversations.py` for human evaluation "
                    "against `human_eval_rubric.md`.\n"]

    per_scenario_latency = {}

    for name, turns in SCENARIOS.items():
        text, latencies = run_scenario(name, turns)
        full_output.append(text)
        full_output.append("\n---\n")
        all_latencies.extend(latencies)
        per_scenario_latency[name] = latencies

    out_path = os.path.join(OUT_DIR, "sample_transcripts.md")
    with open(out_path, "w") as f:
        f.write("\n".join(full_output))

    summary = {
        "total_turns_with_latency": len(all_latencies),
        "avg_latency_ms": round(sum(all_latencies) / len(all_latencies), 1) if all_latencies else None,
        "max_latency_ms": max(all_latencies) if all_latencies else None,
        "min_latency_ms": min(all_latencies) if all_latencies else None,
        "turns_over_2000ms_budget": sum(1 for l in all_latencies if l >= 2000),
        "per_scenario_latency_ms": per_scenario_latency,
    }
    with open(os.path.join(OUT_DIR, "latency_summary.json"), "w") as f:
        json.dump(summary, f, indent=2)

    print(f"Wrote transcripts to {out_path}")
    print(f"Latency summary: {summary}")



if __name__ == "__main__":
    main()


